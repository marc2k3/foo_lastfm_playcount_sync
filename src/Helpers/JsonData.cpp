#include "PCH.hpp"
#include "JsonData.hpp"

std::filesystem::path JsonData::GetFSPath(const fb2k::stringRef& path) noexcept
{
	const auto native_path = filesystem::g_get_native_path(path->c_str());
	auto wpath = pfc::wideFromUTF8(native_path);
	return wpath.c_str();
}

uint32_t JsonData::GetUint32(JSON& json) noexcept
{
	if (json.is_number_unsigned())
		return json.get<uint32_t>();
	else
		return 0u;
}

void JsonData::Export(const fb2k::stringRef& path) noexcept
{
	auto& hm = HashManager::get();
	const auto hashes = hm.get_library_hashes();
	auto data = JSON::array();

	for (const metadb_index_hash hash : hashes)
	{
		const auto f = hm.get_fields(hash);

		if (!f)
			continue;

		JSON json;
		json["hash"] = hash;

		if (f.first_played > 0u)
			json["lfm_first_played"] = f.first_played;

		if (f.last_played > 0u)
			json["lfm_last_played"] = f.last_played;

		if (f.loved > 0u)
			json["lfm_loved"] = f.loved;

		if (f.playcount > 0u)
			json["lfm_playcount"] = f.playcount;

		data.emplace_back(json);
	}

	if (data.size() > 0uz)
	{
		auto fs_path = GetFSPath(path);
		auto stream = std::ofstream(fs_path, std::ios::binary);

		if (stream.is_open())
		{
			stream << data.dump();

			Message::popup("{} records exported succesfully.", data.size());
		}
	}
	else
	{
		Message::popup("Nothing found to export.");
	}
}

void JsonData::Import(const fb2k::stringRef& path) noexcept
{
	std::string content;
	auto fs_path = GetFSPath(path);
	auto stream = std::ifstream(fs_path);

	if (stream.is_open())
	{
		std::string line;

		while (std::getline(stream, line))
		{
			content += line;
		}
	}

	if (content.empty())
	{
		Message::popup("The selected file was empty or there was an unexpected read error.");
		return;
	}

	auto records = JSON::parse(content, nullptr, false);

	if (!records.is_array())
	{
		Message::popup("Unexpected JSON parse error.");
		return;
	}

	lfm::List to_refresh;
	auto& hm = HashManager::get();
	const auto hashes = hm.get_library_hashes();
	auto transaction_ptr = HashManager::api()->begin_transaction();

	for (auto&& record : records)
	{
		auto& jhash = record["hash"];

		if (!jhash.is_number_unsigned())
			continue; // probably not a file generated by us but we'll persist

		const auto hash = jhash.get<uint64_t>();

		if (hashes.count(hash) == 0uz)
			continue; // hash not found in library

		lfm::Fields f;
		f.first_played = GetUint32(record["lfm_first_played"]);
		f.last_played = GetUint32(record["lfm_last_played"]);
		f.loved = GetUint32(record["lfm_loved"]);
		f.playcount = GetUint32(record["lfm_playcount"]);

		if (f)
		{
			hm.set_fields(transaction_ptr, hash, f);
			to_refresh.add_item(hash);
		}
	}

	if (to_refresh.get_count() > 0uz)
	{
		transaction_ptr->commit();
		hm.refresh(to_refresh);

		Message::popup("{} records were imported.", to_refresh.get_count());
	}
	else
	{
		Message::popup("The selected JSON file did not match any Media Library items.");
	}
}
